const UPDATE_ID = "audit-fixes-2026-09-16";
export function updateAuditFixes(dataDir) {
  const marker = path.join(dataDir, `.catalog-update-${UPDATE_ID}`);
  if (fs.existsSync(marker)) return false;
  const read = (name) => JSON.parse(fs.readFileSync(path.join(dataDir, name), "utf8"));
  const products = read("products.json");
  const news = read("news.json");
  for (const [slug, pack] of Object.entries(PACKAGES)) {
    const product = products.find((p) => p.slug === slug);
    if (!product) throw new Error(`Не найден товар для уточнения комплектности: ${slug}`);
    Object.assign(product, pack);
  }
  for (const product of products) {
    if (product.slug === "hid-ksenonovaya-lampa-h4-3000-3200lm-5000-6000k-23000vt-zeus-857896") {
      product.title = product.title.replace(/\s+23000\s*Вт(?=\s|$)/iu, "");
    }
  }
  const newModels = news.find((n) => n.slug === "novinki-momo-2026");
  if (newModels) newModels.productSlugs = [
    "estradnye-kolonki-20sm-v-mashinu-he-810-916179",
    "dinamiki-estradnye-momo-he-815-20sm",
    "dinamiki-estradnye-zeus-mr-8-1-20sm",
  ];
  for (const item of news) {
    if (ARTICLES[item.slug] && !item.body?.trim()) item.body = ARTICLES[item.slug];
  }
  const backupDir = path.join(dataDir, "backups", UPDATE_ID);
  fs.mkdirSync(backupDir, { recursive: true });
  for (const [name, value] of [["products.json", products], ["news.json", news]]) {
    const file = path.join(dataDir, name);
    const backup = path.join(backupDir, name);
    if (!fs.existsSync(backup)) fs.copyFileSync(file, backup);
    const temporary = `${file}.${UPDATE_ID}.tmp`;
    fs.writeFileSync(temporary, `${JSON.stringify(value, null, 2)}\n`);
    fs.renameSync(temporary, file);
  }
  fs.writeFileSync(marker, `${new Date().toISOString()}\n`);
  return true;
}

