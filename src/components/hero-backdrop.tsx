/*
  Фон первого экрана — переливающаяся звуковая линия.

  Раньше её считал фрагментный шейдер через three.js, и это стоило 512 КБ —
  треть всего клиентского кода ради декорации. Библиотека убрана, картинка
  осталась.

  Откуда взялась палитра. Светлый вариант шейдера считал `1.0 - vec3(r,g,b)`,
  то есть вычитал свечение из белого. Убрать красный канал — остаётся голубой,
  зелёный — пурпурный, синий — жёлтый; а множители (1 ± distortion) разводили
  каналы тем сильнее, чем дальше от центра. Отсюда мягкая спектральная кайма,
  расходящаяся к краям, — не «радуга», а субтрактивная развёртка.

  Здесь то же самое набирается веером сдвинутых копий одной кривой: цвета идут
  по спектру, шаг между ними меньше размытия, поэтому они сливаются в одну
  ленту без ступенек.

  Движение. В шейдере это `sin(x + time)` — чистый сдвиг по горизонтали и
  ничего больше. Значит его точно повторяет анимация translateX, а содержимое
  остаётся неподвижным: размытие считается один раз при первой отрисовке,
  дальше слой только двигает композитор. Кривая построена на два периода, и
  сдвиг ровно на период замыкается без стыка.
*/

/**
 * Кривая на два периода: сдвиг ровно на период замыкается без стыка.
 * Описана один раз — ленты различаются только сдвигом по вертикали, который
 * задаётся атрибутом y у <use>. Иначе восемь почти одинаковых путей занимали
 * бы 19 КБ разметки на каждой загрузке главной вместо трёх.
 */
const wavePath = (() => {
  const period = 1200;
  const mid = 200;
  const amp = 100; // yScale 0.5 шейдера, где половина высоты равна 1
  const pts: string[] = [];
  for (let x = 0; x <= period * 2; x += 12) {
    const t = ((x - period) / period) * Math.PI * 2;
    pts.push(`${x === 0 ? "M" : "L"}${x} ${(mid + Math.sin(t) * amp).toFixed(1)}`);
  }
  return pts.join(" ");
})();

/*
  Веер по спектру. Видимая ширина ленты складывается из трёх слагаемых:
  разброс копий (13 × 7) + толщина обводки (40) + размытие с обеих сторон.
  В сумме около 150 единиц из 400 — те же 38% высоты, что и на исходнике.
  Шаг между соседями меньше размытия, поэтому переходы непрерывны, а края
  уходят в прозрачность, чтобы лента растворялась, а не обрывалась.
*/
const BANDS = [
  { y: -39, color: "#ffd95c", o: 0.62 },
  { y: -26, color: "#ffab33", o: 0.74 },
  { y: -13, color: "#ff7a45", o: 0.74 },
  { y: 0, color: "#ff4f7a", o: 0.72 },
  { y: 13, color: "#d955cf", o: 0.72 },
  { y: 26, color: "#7b7ee8", o: 0.7 },
  { y: 39, color: "#3fa5ec", o: 0.64 },
  { y: 52, color: "#4fd2e8", o: 0.46 },
];

export function HeroBackdrop() {
  return (
    <div className="pointer-events-none absolute inset-0 overflow-hidden">
      <svg
        aria-hidden="true"
        className="hero-wave absolute inset-0 h-full w-full"
        viewBox="0 0 1200 400"
        preserveAspectRatio="none"
        fill="none"
      >
        {/*
          Два слоя не для вида, а ради стоимости: размытие висит на внутренней
          группе, содержимое которой неподвижно, поэтому считается один раз и
          дальше берётся готовой текстурой. Двигается внешняя — только
          transform, работа уходит на композитор. Если повесить размытие на
          ту же группу, что и движение, браузер пересчитывал бы его покадрово.
        */}
        <defs>
          <path id="momo-wave" d={wavePath} />
        </defs>
        <g className="hero-wave__track">
          <g className="hero-wave__ink">
            {BANDS.map((b) => (
              <use
                key={b.y}
                href="#momo-wave"
                y={b.y}
                stroke={b.color}
                strokeOpacity={b.o}
                strokeWidth="40"
                strokeLinecap="round"
              />
            ))}
          </g>
        </g>
      </svg>
    </div>
  );
}
