import type { NextConfig } from "next";

/*
  Версия сборки приходит переменной окружения BUILD_REVISION — её ставит
  scripts/deploy.sh перед сборкой. Раньше конфиг сам вызывал `git rev-parse`,
  но любые обращения к файловой системе отсюда заставляют сборщик тянуть в
  трассировку весь проект (предупреждение «unexpected file in NFT list»).
*/
const nextConfig: NextConfig = {
  // На сервере новая версия собирается в отдельную папку. Запущенный Next
  // продолжает читать предыдущую сборку и не падает с 502, пока идёт build.
  distDir: process.env.NEXT_DIST_DIR || ".next",
  env: {
    BUILD_REVISION: process.env.BUILD_REVISION ?? "dev",
    BUILD_TIME: new Date().toISOString(),
  },
  // nodemailer и sharp работают только в Node (sharp в том числе загружает
  // detect-libc, которому нужен child_process). Оставляем их внешними, чтобы
  // dev-сборщик не пытался протащить нативные серверные зависимости в бандл.
  serverExternalPackages: ["nodemailer", "sharp"],

  /*
    Картинки товаров.

    AVIF и WebP: снимки в каталоге — фото на белом, они жмутся в AVIF примерно
    вдвое против JPEG при той же картинке. Порядок важен, браузер берёт первый
    поддерживаемый.

    Набор ширин сведён к тем, что реально просит вёрстка (см. sizes в
    product-image.tsx): плитка каталога, две колонки на телефоне, карточка
    товара и логотип на первом экране. Лишние ширины — это лишние варианты,
    которые сервер пересобирает и хранит.

    minimumCacheTTL — год: файл со снимком не меняется, а при замене товара
    меняется и его имя.
  */
  images: {
    formats: ["image/avif", "image/webp"],
    deviceSizes: [360, 420, 640, 828, 1080, 1200, 1600],
    imageSizes: [64, 96, 128, 256, 384],
    minimumCacheTTL: 31536000,
  },

  /*
    lucide-react отдаёт иконки одним индексом на две тысячи модулей. Без этой
    строки в бандл попадает разбор всего индекса, хотя используется около
    тридцати иконок; с ней каждый импорт превращается в прямую ссылку на файл
    нужной иконки.
  */
  experimental: {
    // Hash-based CSP keeps public pages statically cacheable. Nonce-based CSP
    // requires request-time rendering for every page in Next.js.
    sri: { algorithm: "sha256" },
    optimizePackageImports: ["lucide-react"],
    /*
      Загрузка фото товара идёт серверным действием, а у server actions тело по
      умолчанию ограничено 1 МБ. Несколько снимков с телефона это легко
      превышают, и сохранение падало серверной ошибкой ещё ДО обработки — то
      есть раньше проверки размера в image-pipeline. Это лимит на ВЕСЬ запрос
      «Сохранить», поэтому он выше, чем на один файл (20 МБ в image-pipeline):
      три тяжёлых фото или пачка обычных должны помещаться. Панель под паролем,
      поэтому злоупотребить нечем.
    */
    serverActions: {
      bodySizeLimit: "60mb",
    },
  },

  // Карты кода наружу не отдаём: это лишние мегабайты на каждом выкате.
  productionBrowserSourceMaps: false,

  // Заголовок X-Powered-By: Next.js не отдаём: незачем подсказывать ботам,
  // сканирующим сеть по «уязвим такой-то фреймворк», что стек именно этот.
  poweredByHeader: false,

  /*
    Заголовки безопасности, одинаковые для всех ответов.

    Content-Security-Policy живёт в src/proxy.ts рядом с проверкой доступа к
    панели. Политика статическая, а целостность production-бандлов Next
    подтверждает SRI-хешами.
  */
  async headers() {
    // immutable-кэш на сборочные файлы включаем только в проде: в разработке
    // он заставлял браузер держать устаревший JS и ломал горячую перезагрузку
    // (Next об этом и предупреждает в консоли dev-сервера).
    const prod = process.env.NODE_ENV === "production";
    return [
      {
        source: "/:path*",
        headers: [
          // Форму входа и подтверждение заказа нельзя затянуть в чужой iframe.
          // Карты Яндекса это не задевает: заголовок про нас в чужой рамке,
          // а не про чужое внутри нас.
          { key: "X-Frame-Options", value: "DENY" },
          // Браузер не додумывает тип файла за сервером.
          { key: "X-Content-Type-Options", value: "nosniff" },
          // Наружу уходит только домен, без пути: адреса кабинета и страницы
          // возврата с оплаты содержат номер заказа и метку.
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          // Геолокация нужна только для поиска ближайших ПВЗ Ozon; камеру и микрофон запрещаем.
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=(self), payment=()",
          },
          /*
            HSTS на два года. Nginx и так уводит с http на https, но 301
            выполняется уже после запроса — заголовок избавляет от самого
            первого незащищённого захода.

            includeSubDomains — сертификат выпущен на momo-eq.ru и www,
            других поддоменов нет. preload не ставим: попадание в списки
            браузеров отменяется месяцами.
          */
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains",
          },
        ],
      },
      /*
        Сборочные файлы лежат под именами с хешем содержимого: меняется
        содержимое — меняется имя. Значит, их можно кэшировать навсегда и
        больше не спрашивать сервер: при выкате браузер просто запросит новые
        имена. Без этого заголовка каждый повторный заход перепроверял весь
        JS и CSS условными запросами.
      */
      ...(prod
        ? [
            {
              source: "/fonts/:path*",
              headers: [
                {
                  key: "Cache-Control",
                  value: "public, max-age=31536000, immutable",
                },
              ],
            },
          ]
        : []),
      /*
        Снимки товаров отдаёт свой обработчик (/media). Имя файла привязано к
        товару и при замене снимка меняется, поэтому неделя в кэше браузера и
        месяц у посредника — с правом отдать устаревшее, пока обновляется.
      */
      {
        source: "/media/:path*",
        headers: [
          {
            key: "Cache-Control",
            value: "public, max-age=604800, s-maxage=2592000, stale-while-revalidate=86400",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
